"""
工程规范智能问答 RAG Service —— 优化版提示词编排

核心改进：
1. System Prompt 与 Context 分离（指令/证据解耦）
2. 要求逐字引用规范原文，禁止改写
3. 结构化输出（直接回答 + 原文引用 + 条款说明 + 参考来源）
4. 禁止"基于自身知识"补充规范内容，降低幻觉
5. 支持多条款、强制性条文标注、条款冲突处理
6. Context 结构化，携带元数据（规范名/条款号/条文类型/相关度）
"""


# ============================================================
# 1. System Prompt —— 角色定义 + 规则 + 输出格式（不含上下文）
# ============================================================
SYSTEM_PROMPT = """你是一名工程规范领域的智能问答助手，专门基于检索到的规范条文回答用户问题。

## 核心原则
1. **仅依据检索到的规范条文回答**，不得使用自身知识编造或补充规范内容。
2. **引用规范原文**，引用时使用「」符号包裹，不得改写、概括或意译。
3. **精确标注出处**，格式：《规范名称》第X章第X条（或第X.X.X条）。
4. 若检索结果与问题无关或不足，必须明确回答"未在知识库中检索到相关规范条款"，不得臆造。

## 回答结构（严格按以下格式输出）

### 一、直接回答
用1-3句话直接回答用户问题，语言简练。

### 二、规范原文引用
逐条列出相关条款原文，每条格式如下：
> 「规范原文内容（逐字引用，不得改写，保留原标点）」
> ——《规范名称》第X.X.X条 【强制性条文 / 推荐性条文 / 一般条文】

### 三、条款说明（可选）
对引用条款做简要说明，帮助用户理解，但不得与原文矛盾或超出原文范围。

### 四、参考来源
- 《规范名称1》第X.X.X条
- 《规范名称2》第X.X.X条

## 特殊情况处理
- **多条相关条款**：按相关度从高到低全部列出，不得遗漏。
- **条款冲突**：如不同规范对同一问题有不同规定，全部列出并注明差异，优先标注强制性条文。
- **强制性条文**：在出处后标注【强制性条文】。
- **问题模糊**：如用户问题不够明确，先列出可能相关的条款，再请用户确认具体场景。
- **检索不足**：明确说明"未在知识库中检索到相关规范条款"，可建议用户更换关键词或确认知识库范围，但不得自行补充规范内容。

## 禁止事项
- 不得编造未在检索结果中出现的规范编号、条款号或条文内容。
- 不得将检索到的条文内容改写后再引用。
- 不得省略条款中的限定条件、例外情况、适用范围。
- 检索结果不足时，不得用自身知识"补充"规范内容。
"""


# ============================================================
# 2. 结构化上下文构建器 —— 将检索结果格式化为带元数据的块
# ============================================================
def build_structured_context(retrieved_chunks: list[dict]) -> str:
    """
    将检索到的 chunk 列表格式化为结构化上下文文本。

    每个 chunk 应包含以下字段：
      - doc_name:      规范名称（含编号，如《钢结构工程施工质量验收标准》GB 50205-2020）
      - clause_id:     条款编号（如 第5.2.4条）
      - clause_type:   条文类型（强制性条文 / 推荐性条文 / 一般条文）
      - content:       条文原文
      - score:         检索相关度分数（可选）
      - chapter:       所在章节（可选，如 第5章 焊接工程）
    """
    blocks = []
    for i, chunk in enumerate(retrieved_chunks, 1):
        chapter_line = f"所在章节：{chunk['chapter']}\n" if chunk.get("chapter") else ""
        score_line = f"相关度：{chunk['score']:.2f}\n" if chunk.get("score") is not None else ""

        block = f"""【检索结果 {i}】
规范名称：《{chunk['doc_name']}》
条款编号：{chunk['clause_id']}
条文类型：{chunk.get('clause_type', '一般条文')}
{chapter_line}{score_line}原文内容：{chunk['content']}"""
        blocks.append(block.strip())

    return "\n\n".join(blocks)


# ============================================================
# 3. 用户消息构建器 —— 上下文 + 用户问题
# ============================================================
def build_user_message(context_block: str, user_query: str) -> str:
    """
    将结构化上下文和用户问题组装为 user message。
    System Prompt 作为独立的 system 角色消息发送，不与此混合。
    """
    return f"""## 检索到的规范条文

{context_block}

---

## 用户问题
{user_query}"""


# ============================================================
# 4. 完整调用示例
# ============================================================
def call_rag(llm_client, retrieved_chunks: list[dict], user_query: str) -> str:
    """
    完整的 RAG 调用流程。

    参数:
        llm_client:       你的 LLM 客户端（OpenAI / 自研 / 其他）
        retrieved_chunks: 检索到的规范条文 chunk 列表
        user_query:       用户原始问题
    """
    context_block = build_structured_context(retrieved_chunks)
    user_message = build_user_message(context_block, user_query)

    response = llm_client.chat(
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_message},
        ],
        temperature=0.1,   # 低温度，保证规范引用的准确性和一致性
    )
    return response


